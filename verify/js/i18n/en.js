/**
 * en.js — English source string table (WP12). Phase 1 source and review language.
 *
 * Shape: EN[key] = { text, loc, ctx, group }
 *   loc   — location identifier (screen / component where it renders)
 *   ctx   — context note for translators (Phase 2 Spanish work)
 *   group — the BUILD-PLAN WP12 string group it belongs to (for the inventory report)
 *
 * Wording sources: the spec's fixed wording is used verbatim where the spec fixes it
 * (opening question, four paths, three stop scripts); CHECK4-RULE §5 and §4.4 wording
 * (frozen, C4-P13); SUPPORTED-NETWORKS user messages (frozen, SN-P8, SN-P10, SN-P11,
 * SN-P12, SN-P13, SN-P15); everything else written for the Desk read-aloud test: one
 * thread, short sentences, plain fact first [Spec §7].
 *
 * No review-process role, federal-role, or agency reference may appear in any value (Gate P-07;
 * enforced by test/boundaries.test.mjs).
 */
const EN = {};
function group(groupName, loc, ctx, entries) {
  for (const [key, val] of Object.entries(entries)) {
    const [text, note] = Array.isArray(val) ? val : [val, ''];
    EN[key] = Object.freeze({ text, loc, ctx: note ? `${ctx} ${note}` : ctx, group: groupName });
  }
}

